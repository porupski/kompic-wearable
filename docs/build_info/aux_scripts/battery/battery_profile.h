// Linear-interpolated SoC estimate from measured Vbat.
// Returns 0-100. Rounds toward empty (conservative).
static inline uint8_t batt_soc_from_mv(uint16_t mv) {
    if (mv <= batt_ocv_mv[0])   return 0;
    if (mv >= batt_ocv_mv[100]) return 100;
    for (uint8_t i = 1; i <= 100; i++) {
        if (mv < batt_ocv_mv[i]) return (uint8_t)(i - 1);
    }
    return 100;
}
